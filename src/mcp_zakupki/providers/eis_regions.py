def _normalize_region(value: str) -> str:
    key = " ".join(value.casefold().replace("ё", "е").split()).strip(". ")
    key = re.sub(r"^г(?:\.\s*|\s+)", "", key)
    return re.sub(r"\bобл\.?$", "область", key)


_REGION_BY_NAME = {_normalize_region(name): code for code, name in REGION_NAMES.items()}


def normalize_customer_regions(regions: list[str]) -> list[str]:
    codes = list(dict.fromkeys(validate_region_code(region) for region in regions))
    unknown = [code for code in codes if code not in REGION_NAMES]
    if unknown:
        raise ValidationError(
            "Регион отсутствует в классификаторе местоположений заказчика ЕИС.",
            details={"region_codes": unknown},
        )
    return codes


def customer_region(region_name: str | None, address: str | None) -> tuple[str | None, str | None]:
    """Определить код только по явно указанному региону или части адреса заказчика."""
    values = [region_name] if region_name else []
    if address:
        values.extend(address.split(","))
    for value in values:
        code = _REGION_BY_NAME.get(_normalize_region(value))
        if code:
            return code, REGION_NAMES[code]
    return None, region_name
